package dev.redfox.lookpe.statement

import android.graphics.Canvas
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import dev.redfox.lookpe.Money
import java.io.OutputStream
import java.time.Instant
import java.time.format.DateTimeFormatter
import java.util.Locale

/**
 * Draws a [Statement] as an A4 PDF, laid out like a bank statement: a summary, a day-by-day table,
 * then every payment oldest first with a running total. Tables carry on over as many pages as needed
 * and repeat their header; every page has a "Page x of y" footer.
 */
object StatementPdf {
    private const val W = 595
    private const val H = 842
    private const val MARGIN = 40f
    private const val FOOTER_Y = H - 28f
    private const val BOTTOM = H - 52f
    private const val TITLE_AND_HEAD = 20f + 16f

    private val INK = 0xFF1B1F23.toInt()
    private val MUTED = 0xFF6B7280.toInt()
    private val ACCENT = 0xFF047857.toInt()
    private val TINT = 0xFFE8F5EF.toInt()
    private val LINE = 0xFFD9DEE3.toInt()

    private val dateFmt = DateTimeFormatter.ofPattern("d MMM yyyy", Locale.ENGLISH)
    private val shortDateFmt = DateTimeFormatter.ofPattern("dd MMM yy", Locale.ENGLISH)
    private val dayFmt = DateTimeFormatter.ofPattern("EEE, d MMM yyyy", Locale.ENGLISH)
    private val timeFmt = DateTimeFormatter.ofPattern("hh:mm a", Locale.ENGLISH)
    private val stampFmt = DateTimeFormatter.ofPattern("d MMM yyyy, h:mm a", Locale.ENGLISH)

    fun write(statement: Statement, out: OutputStream) {
        // Pass 1 only counts the pages, so pass 2 can print "Page x of y".
        val pages = Renderer(statement, totalPages = 0).run { draw(); document.close(); pageCount }
        val doc = Renderer(statement, totalPages = pages).run { draw(); document }
        try {
            doc.writeTo(out)
        } finally {
            doc.close()
        }
    }

    private class Renderer(val s: Statement, val totalPages: Int) {
        val document = PdfDocument()
        var pageCount = 0
        private var page: PdfDocument.Page? = null
        private lateinit var c: Canvas
        private var y = 0f

        private fun paint(size: Float, color: Int = INK, bold: Boolean = false, mono: Boolean = false) = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            textSize = size
            this.color = color
            typeface = when {
                mono -> Typeface.MONOSPACE
                bold -> Typeface.create("sans-serif-medium", Typeface.BOLD)
                else -> Typeface.create("sans-serif", Typeface.NORMAL)
            }
        }
        private val body = paint(8.5f)
        private val bodyMono = paint(7.5f, mono = true)
        private val bodyBold = paint(8.5f, bold = true)
        private val head = paint(8f, MUTED, bold = true)
        private val line = Paint().apply { color = LINE; strokeWidth = 0.6f }
        private val fill = Paint()

        fun draw() {
            newPage()
            header()
            summary()
            dailyTable()
            transactionTable()
            finishPage()
        }

        private fun newPage() {
            pageCount++
            page = document.startPage(PdfDocument.PageInfo.Builder(W, H, pageCount).create())
            c = page!!.canvas
            y = MARGIN
        }

        private fun finishPage() {
            val foot = paint(7.5f, MUTED)
            c.drawLine(MARGIN, FOOTER_Y - 12, W - MARGIN, FOOTER_Y - 12, line)
            c.drawText("Generated by LookPe from PhonePe Business notifications on this phone", MARGIN, FOOTER_Y, foot)
            val label = if (totalPages > 0) "Page $pageCount of $totalPages" else "Page $pageCount"
            c.drawText(label, W - MARGIN - foot.measureText(label), FOOTER_Y, foot)
            document.finishPage(page)
        }

        /** Starts a new page when [height] more points won't fit; true if it did. */
        private fun ensure(height: Float): Boolean {
            if (y + height <= BOTTOM) return false
            finishPage()
            newPage()
            return true
        }

        private fun header() {
            val title = paint(20f, ACCENT, bold = true)
            c.drawText("LookPe", MARGIN, y + 16, title)
            val sub = paint(11f, INK, bold = true)
            val label = "Payment statement"
            c.drawText(label, W - MARGIN - sub.measureText(label), y + 14, sub)
            y += 30
            c.drawLine(MARGIN, y, W - MARGIN, y, Paint().apply { color = ACCENT; strokeWidth = 1.5f })
            y += 16
            val key = paint(8.5f, MUTED)
            fun info(k: String, v: String) {
                c.drawText(k, MARGIN, y, key)
                c.drawText(v, MARGIN + 80, y, bodyBold)
                y += 14
            }
            info("Period", "${dateFmt.format(s.from)} to ${dateFmt.format(s.to)}")
            info("Generated", stampFmt.format(Instant.ofEpochMilli(s.generatedAt).atZone(s.zone)))
            info("Account", "PhonePe Business · money received")
            y += 6
        }

        private fun summary() {
            val gap = 8f
            val boxW = (W - 2 * MARGIN - 2 * gap) / 3
            val boxH = 44f
            val items = listOf(
                "TOTAL RECEIVED" to "₹" + Money.plain(s.totalPaise),
                "PAYMENTS" to s.count.toString(),
                "AVERAGE PAYMENT" to "₹" + Money.plain(s.averagePaise),
                "HIGHEST PAYMENT" to (s.highest?.let { "₹" + Money.plain(it.amountPaise) } ?: "-"),
                "BEST DAY" to (s.bestDay?.let { "${shortDateFmt.format(it.date)} · ₹${Money.plain(it.totalPaise)}" } ?: "-"),
                "DAYS WITH PAYMENTS" to "${s.days.size} of ${java.time.temporal.ChronoUnit.DAYS.between(s.from, s.to) + 1}",
            )
            val label = paint(7f, MUTED, bold = true)
            val value = paint(12f, INK, bold = true)
            items.chunked(3).forEach { row ->
                row.forEachIndexed { i, (k, v) ->
                    val x = MARGIN + i * (boxW + gap)
                    fill.color = TINT
                    c.drawRoundRect(x, y, x + boxW, y + boxH, 6f, 6f, fill)
                    c.drawText(k, x + 10, y + 15, label)
                    var size = 12f
                    while (value.measureText(v) > boxW - 20 && size > 7f) value.textSize = --size
                    c.drawText(v, x + 10, y + 33, value)
                    value.textSize = 12f
                }
                y += boxH + gap
            }
            y += 6
        }

        private fun sectionTitle(text: String) {
            c.drawText(text, MARGIN, y + 10, paint(11f, ACCENT, bold = true))
            y += 20
        }

        /** Column header strip; [cols] are (title, x offset from the left margin, right aligned?). */
        private fun tableHead(cols: List<Col>) {
            fill.color = TINT
            c.drawRect(MARGIN, y, W - MARGIN, y + 16, fill)
            cols.forEach { col -> text(col, col.title, y + 11, head) }
            y += 16
        }

        private class Col(val title: String, val x: Float, val width: Float, val right: Boolean = false)

        private fun text(col: Col, value: String, baseline: Float, p: Paint) {
            val shown = fit(value, p, col.width - 4)
            val x = if (col.right) MARGIN + col.x + col.width - p.measureText(shown) else MARGIN + col.x + 2
            c.drawText(shown, x, baseline, p)
        }

        private fun fit(value: String, p: Paint, max: Float): String {
            if (p.measureText(value) <= max) return value
            val n = p.breakText(value, true, max - p.measureText("…"), null)
            return value.take(n).trimEnd() + "…"
        }

        private fun dailyTable() {
            if (s.days.isEmpty()) return
            val cols = listOf(Col("DATE", 0f, 200f), Col("PAYMENTS", 200f, 120f, right = true), Col("TOTAL (₹)", 320f, 195f, right = true))
            ensure(TITLE_AND_HEAD + 15f)
            sectionTitle("Day by day")
            tableHead(cols)
            s.days.forEach { d ->
                if (ensure(15f)) tableHead(cols)
                text(cols[0], dayFmt.format(d.date), y + 10.5f, body)
                text(cols[1], d.count.toString(), y + 10.5f, body)
                text(cols[2], Money.plain(d.totalPaise), y + 10.5f, body)
                y += 15
                c.drawLine(MARGIN, y, W - MARGIN, y, line)
            }
            fill.color = TINT
            c.drawRect(MARGIN, y, W - MARGIN, y + 16, fill)
            text(cols[0], "Total", y + 11, bodyBold)
            text(cols[1], s.count.toString(), y + 11, bodyBold)
            text(cols[2], Money.plain(s.totalPaise), y + 11, bodyBold)
            y += 30
        }

        private fun transactionTable() {
            val cols = listOf(
                Col("DATE", 0f, 62f), Col("TIME", 62f, 50f), Col("PAYER", 112f, 112f), Col("TRANSACTION ID", 224f, 123f),
                Col("AMOUNT (₹)", 347f, 80f, right = true), Col("RUNNING TOTAL (₹)", 427f, 88f, right = true),
            )
            ensure(TITLE_AND_HEAD + 15f)
            sectionTitle("Transactions")
            if (s.rows.isEmpty()) {
                c.drawText("No payments in this period.", MARGIN, y + 10, body)
                return
            }
            tableHead(cols)
            s.rows.forEach { r ->
                if (ensure(15f)) {
                    sectionTitle("Transactions (continued)")
                    tableHead(cols)
                }
                val at = Instant.ofEpochMilli(r.at).atZone(s.zone)
                val base = y + 10.5f
                text(cols[0], shortDateFmt.format(at), base, body)
                text(cols[1], timeFmt.format(at), base, body)
                text(cols[2], r.payer ?: "-", base, body)
                text(cols[3], r.txnId ?: "-", base, bodyMono)
                text(cols[4], Money.plain(r.amountPaise), base, bodyBold)
                text(cols[5], Money.plain(r.runningPaise), base, body)
                y += 15
                c.drawLine(MARGIN, y, W - MARGIN, y, line)
            }
            y += 8
            c.drawText("End of statement", MARGIN, y + 8, paint(8f, MUTED))
        }
    }
}
